@pytest.mark.parametrize("ns,preset_id", [("Citation", "citation-date-between"), ("Media", "media-date-between")])
def test_date_between(db, preset_by_id, ns, preset_id):
    """Like test_event_date_between: the expected set is the plain sortval
    range the preset claims, not gramps-core's fuzzy Date.match()."""
    start, end = "1 Jan 1800", "31 Dec 2000"
    lo, hi = date_parser.parse(start), date_parser.parse(end)
    objs = objects(db, ns)
    expected = {o.handle for o in objs if o.date.sortval != 0 and lo.sortval <= o.date.sortval <= hi.sortval}
    actual = goql_matching_handles(db, ns, fill(preset_by_id[preset_id], startDate=start, endDate=end), objs)
    assert actual == expected and expected


def test_citation_source_id_is(db, preset_by_id):
    """gramps-core 6.0's HasSourceIdOf never matches (HasGrampsId's
    selected_handles is never filled in), so this checks what it means."""
    for source in db.iter_sources():
        gid = source.gramps_id
        compare_plain(
            db, "Citation", fill(preset_by_id["citation-source-id-is"], id=gid),
            lambda c: db.get_source_from_handle(c.source_handle).gramps_id == gid, expect_some=False,
        )
    compare_plain(
        db, "Citation", fill(preset_by_id["citation-source-id-is"], id="S0001"),
        lambda c: db.get_source_from_handle(c.source_handle).gramps_id == "S0001",
    )


def test_citation_source_id_matches(db, gramps_user, preset_by_id):
    compare(
        db, "Citation", fill(preset_by_id["citation-source-id-matches"], pattern=r"s000[01]"),
        citation_rules.RegExpSourceIdOf([r"s000[01]"], use_regex=True), gramps_user,
    )


